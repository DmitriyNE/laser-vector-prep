//! Synthetic Gerber (RS-274X / X2) fixtures, written by a tiny emitter so the files are
//! independent of the core's reader. Coordinates use `FSLAX46Y46` in millimetres.

use std::f64::consts::PI;

use serde_json::{Value, json};

pub struct GerberFixture {
    pub name: &'static str,
    pub description: &'static str,
    /// X2 `TF.FileFunction` value, if the file declares one.
    pub function: Option<&'static str>,
    pub text: String,
    pub expect: Value,
    pub notes: Vec<&'static str>,
}

impl GerberFixture {
    pub fn file_name(&self) -> String {
        format!("gerber/{}.gbr", self.name)
    }
}

struct Writer {
    out: String,
}

fn coord(v: f64) -> String {
    format!("{}", (v * 1e6).round() as i64)
}

impl Writer {
    fn new(function: Option<&str>) -> Writer {
        let mut w = Writer { out: String::new() };
        w.line("G04 generated by lvp-fixtures (`just fixtures`); do not edit*");
        w.line("%TF.GenerationSoftware,lvp,lvp-fixtures,0.1*%");
        if let Some(f) = function {
            w.line(&format!("%TF.FileFunction,{f}*%"));
        }
        w.line("%TF.FilePolarity,Positive*%");
        w.line("%FSLAX46Y46*%");
        w.line("%MOMM*%");
        w.line("G75*");
        w
    }

    fn line(&mut self, s: &str) {
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn ad_circle(&mut self, code: u32, d: f64, hole: Option<f64>) {
        match hole {
            Some(h) => self.line(&format!("%ADD{code}C,{d}X{h}*%")),
            None => self.line(&format!("%ADD{code}C,{d}*%")),
        }
    }

    fn ad_rect(&mut self, code: u32, w: f64, h: f64) {
        self.line(&format!("%ADD{code}R,{w}X{h}*%"));
    }

    fn ad_obround(&mut self, code: u32, w: f64, h: f64) {
        self.line(&format!("%ADD{code}O,{w}X{h}*%"));
    }

    fn ad_polygon(&mut self, code: u32, d: f64, n: u32, rot: f64) {
        self.line(&format!("%ADD{code}P,{d}X{n}X{rot}*%"));
    }

    fn am(&mut self, name: &str, body: &[&str]) {
        let mut s = format!("%AM{name}*");
        for b in body {
            s.push_str(b);
            s.push('*');
        }
        s.push('%');
        self.line(&s);
    }

    fn ad_macro(&mut self, code: u32, name: &str, mods: &[f64]) {
        let m: Vec<String> = mods.iter().map(|v| format!("{v}")).collect();
        if m.is_empty() {
            self.line(&format!("%ADD{code}{name}*%"));
        } else {
            self.line(&format!("%ADD{code}{name},{}*%", m.join("X")));
        }
    }

    fn select(&mut self, code: u32) {
        self.line(&format!("D{code}*"));
    }

    fn flash(&mut self, x: f64, y: f64) {
        self.line(&format!("X{}Y{}D03*", coord(x), coord(y)));
    }

    fn mv(&mut self, x: f64, y: f64) {
        self.line(&format!("X{}Y{}D02*", coord(x), coord(y)));
    }

    fn line_to(&mut self, x: f64, y: f64) {
        self.line(&format!("G01X{}Y{}D01*", coord(x), coord(y)));
    }

    /// Arc to `(x, y)` with centre offset `(i, j)` from the current point.
    fn arc_to(&mut self, x: f64, y: f64, i: f64, j: f64, ccw: bool) {
        let g = if ccw { "G03" } else { "G02" };
        self.line(&format!(
            "{g}X{}Y{}I{}J{}D01*",
            coord(x),
            coord(y),
            coord(i),
            coord(j)
        ));
    }

    fn region(&mut self, points: &[(f64, f64)]) {
        self.line("G36*");
        let (x0, y0) = points[0];
        self.mv(x0, y0);
        for &(x, y) in &points[1..] {
            self.line_to(x, y);
        }
        self.line_to(x0, y0);
        self.line("G37*");
    }

    fn polarity(&mut self, dark: bool) {
        self.line(if dark { "%LPD*%" } else { "%LPC*%" });
    }

    fn end(mut self) -> String {
        self.line("M02*");
        self.out
    }
}

/// Same copper artwork as `dxf/board-islands.dxf`, as a Gerber top copper layer.
fn board_f_cu() -> GerberFixture {
    let mut w = Writer::new(Some("Copper,L1,Top"));
    w.ad_circle(10, 1.2, None);
    w.ad_circle(11, 0.3, None);
    w.ad_rect(12, 2.0, 2.0);
    w.ad_obround(13, 3.0, 1.0);
    w.ad_circle(14, 0.25, None);
    w.ad_circle(15, 3.0, Some(1.6));
    w.line("G04 two rows of three round pads*");
    w.select(10);
    for &x in &[3.0, 6.0, 9.0] {
        w.flash(x, 2.8);
        w.flash(x, 8.5);
    }
    w.line("G04 trace joining the leftmost pair*");
    w.select(11);
    w.mv(3.0, 3.3);
    w.line_to(3.0, 8.0);
    w.line("G04 two rectangular pads*");
    w.select(12);
    w.flash(16.0, 3.0);
    w.flash(16.0, 8.3);
    w.line("G04 obround slot pad*");
    w.select(13);
    w.flash(12.0, 5.65);
    w.line("G04 free zigzag trace*");
    w.select(14);
    w.mv(14.0, 5.0);
    w.line_to(15.0, 6.3);
    w.line_to(16.0, 5.0);
    w.line_to(17.0, 6.3);
    w.line_to(18.0, 5.0);
    w.line("G04 annulus: round aperture with a hole*");
    w.select(15);
    w.flash(21.0, 5.65);
    GerberFixture {
        name: "board-F_Cu",
        description: "Top copper of the board fixture as Gerber X2: flashes (C, R, O, C with hole), traces as draws.",
        function: Some("Copper,L1,Top"),
        text: w.end(),
        expect: json!({
            "copper_bounds_mm": [2.4, 2.0, 22.5, 9.3],
            "copper_islands": 10,
            "copper_holes": 1,
            "primitives": 12,
        }),
        notes: vec![
            "geometry matches dxf/board-islands.dxf TOP_LAYER so both import paths must agree",
            "the annulus is one flash of a C aperture with a hole: one island with one hole",
        ],
    }
}

/// The board outline drawn as a thin closed contour with quarter-circle corners.
fn board_edge_cuts() -> GerberFixture {
    let mut w = Writer::new(Some("Profile,NP"));
    w.ad_circle(10, 0.05, None);
    w.select(10);
    w.mv(1.0, 0.0);
    w.line_to(24.0, 0.0);
    w.arc_to(25.0, 1.0, 0.0, 1.0, true);
    w.line_to(25.0, 10.3);
    w.arc_to(24.0, 11.3, -1.0, 0.0, true);
    w.line_to(1.0, 11.3);
    w.arc_to(0.0, 10.3, 0.0, -1.0, true);
    w.line_to(0.0, 1.0);
    w.arc_to(1.0, 0.0, 1.0, 0.0, true);
    GerberFixture {
        name: "board-Edge_Cuts",
        description: "Board outline (25 x 11.3 mm, 1 mm corner radius) drawn with a 0.05 mm aperture.",
        function: Some("Profile,NP"),
        text: w.end(),
        expect: json!({
            "paths": 1,
            "closed": true,
            "width_mm": 0.05,
            "length_mm": 2.0 * (25.0 + 11.3) - 8.0 + 2.0 * PI,
            "bounds_mm": [0.0, 0.0, 25.0, 11.3],
        }),
        notes: vec![
            "a draw chain that returns to its start is one closed path; readers must not leave it open",
            "as a named-boundary domain the contour's interior is the board, not the 0.05 mm ring",
        ],
    }
}

/// `∫_0^h sqrt(r² − y²) dy`
fn circle_strip(r: f64, h: f64) -> f64 {
    (h * (r * r - h * h).sqrt() + r * r * (h / r).asin()) / 2.0
}

/// One of everything: regions, clear polarity, step-and-repeat, macro apertures with
/// variables, standard apertures, arcs, aperture blocks and transforms.
fn features() -> GerberFixture {
    let mut w = Writer::new(Some("Other,Features"));
    w.ad_circle(10, 2.0, None);
    w.ad_circle(11, 1.0, None);
    w.ad_circle(12, 1.0, None);
    w.am("THERMAL", &["7,0,0,$1,$2,$3,45"]);
    w.ad_macro(20, "THERMAL", &[4.0, 2.0, 0.5]);
    w.ad_obround(21, 3.0, 1.5);
    w.ad_polygon(22, 2.0, 6, 0.0);
    w.ad_circle(23, 0.2, None);
    w.ad_circle(24, 0.8, None);
    w.am(
        "TRI",
        &["0 right triangle with legs $1", "4,1,3,0,0,$1,0,0,$1,0,0,0"],
    );
    w.ad_macro(40, "TRI", &[2.0]);

    w.line("G04 square region with a cleared circle and a dark island inside it*");
    w.region(&[(0.0, 0.0), (10.0, 0.0), (10.0, 10.0), (0.0, 10.0)]);
    w.polarity(false);
    w.select(10);
    w.flash(5.0, 5.0);
    w.polarity(true);
    w.select(11);
    w.flash(5.0, 5.0);

    w.line("G04 3 x 2 array of 1 mm pads by step and repeat*");
    w.line("%SRX3Y2I5.0J5.0*%");
    w.select(12);
    w.flash(20.0, 0.0);
    w.line("%SR*%");

    w.line("G04 thermal relief macro*");
    w.select(20);
    w.flash(40.0, 5.0);

    w.line("G04 obround and hexagon*");
    w.select(21);
    w.flash(50.0, 5.0);
    w.select(22);
    w.flash(55.0, 5.0);

    w.line("G04 half-circle arc draw*");
    w.select(23);
    w.mv(60.0, 5.0);
    w.arc_to(64.0, 5.0, 2.0, 0.0, true);

    w.line("G04 aperture block of two pads, flashed rotated by 90 degrees*");
    w.line("%ABD30*%");
    w.select(24);
    w.flash(0.0, 0.0);
    w.flash(2.0, 0.0);
    w.line("%AB*%");
    w.line("%LR90*%");
    w.select(30);
    w.flash(70.0, 5.0);
    w.line("%LR0*%");

    w.line("G04 outline macro with a variable*");
    w.select(40);
    w.flash(80.0, 5.0);

    let h = 0.25;
    let thermal = 3.0 * PI - 8.0 * (circle_strip(2.0, h) - circle_strip(1.0, h));
    let area = (100.0 - PI + PI / 4.0)
        + 1.5 * PI
        + thermal
        + (2.25 + 0.5625 * PI)
        + 3.0 * 3f64.sqrt() / 2.0
        + 0.41 * PI
        + 0.32 * PI
        + 2.0;
    GerberFixture {
        name: "features",
        description: "Region with clear/dark compositing, step-and-repeat, thermal and outline macros, obround and polygon apertures, an arc draw, an aperture block with rotation.",
        function: Some("Other,Features"),
        text: w.end(),
        expect: json!({
            "islands": 18,
            "holes": 1,
            "area_mm2": area,
            "bounds_mm": [0.0, -0.5, 82.0, 10.0],
            "thermal_islands": 4,
        }),
        notes: vec![
            "all features are disjoint, so the total area is the sum of the analytic areas",
            "the clear circle is composited in source order: the later dark circle inside it survives",
            "the thermal area is the annulus minus two 0.5 mm bars (closed-form circle strips)",
        ],
    }
}

pub fn all() -> Vec<GerberFixture> {
    vec![board_f_cu(), board_edge_cuts(), features()]
}
