//! Synthetic SVG fixture written by hand-rolled markup (independent of usvg), covering what
//! the spec requires of the SVG reader: mm units with a viewBox, Inkscape layers, shapes,
//! paths with Béziers, nested transforms, `use`, fill rules, strokes and a clip path.

use std::f64::consts::PI;

use serde_json::{Value, json};

pub struct SvgFixture {
    pub name: &'static str,
    pub description: &'static str,
    pub text: String,
    pub expect: Value,
    pub notes: Vec<&'static str>,
}

impl SvgFixture {
    pub fn file_name(&self) -> String {
        format!("svg/{}.svg", self.name)
    }
}

/// Layers `MARK` (stroked linework) and `FILL` (filled shapes), like the DXF open-linework
/// fixture, plus a `CLIPPED` layer, so the general-marking preset binds it directly.
fn marking() -> SvgFixture {
    // Circle from four cubic Béziers (kappa approximation), centre (30, 10), r = 5.
    let k = 0.552_284_75 * 5.0;
    let circle = format!(
        "M 35 10 C 35 {a} {a2} 15 30 15 C {b} 15 25 {a} 25 10 C 25 {c} {b} 5 30 5 C {a2} 5 35 {c} 35 10 Z",
        a = 10.0 + k,
        a2 = 30.0 + k,
        b = 30.0 - k,
        c = 10.0 - k
    );
    let text = format!(
        r##"<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by lvp-fixtures (`just fixtures`); do not edit -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"
     xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"
     width="60mm" height="20mm" viewBox="0 0 60 20" version="1.1">
  <defs>
    <rect id="pad" width="2" height="2" fill="#000000"/>
    <clipPath id="right-half"><rect x="50" y="0" width="10" height="20"/></clipPath>
  </defs>
  <g id="layer1" inkscape:groupmode="layer" inkscape:label="MARK">
    <line x1="2" y1="2" x2="18" y2="2" stroke="#000000" stroke-width="0.2"/>
    <polyline points="2,5 6,9 10,5 14,9 18,5" fill="none" stroke="#000000" stroke-width="0.25"/>
    <path d="M 2 12 Q 10 20 18 12" fill="none" stroke="#000000" stroke-width="0.2"/>
    <g transform="translate(2 15) rotate(-20)">
      <line x1="0" y1="0" x2="10" y2="0" stroke="#000000" stroke-width="0.1"/>
    </g>
  </g>
  <g id="layer2" inkscape:groupmode="layer" inkscape:label="FILL">
    <path d="{circle}" fill="#ff0000"/>
    <path d="M 38 4 L 48 4 L 48 16 L 38 16 Z M 40 6 L 46 6 L 46 14 L 40 14 Z" fill="#0000ff" fill-rule="evenodd"/>
    <g transform="translate(20 3) scale(1.5)">
      <use xlink:href="#pad" x="0" y="0"/>
      <use xlink:href="#pad" x="0" y="4"/>
    </g>
  </g>
  <g id="layer3" inkscape:groupmode="layer" inkscape:label="CLIPPED" clip-path="url(#right-half)">
    <rect x="45" y="5" width="10" height="10" fill="#00aa00"/>
  </g>
</svg>
"##
    );
    let pads = 2.0 * (3.0 * 3.0);
    SvgFixture {
        name: "marking",
        description: "Inkscape-style layers MARK (stroked lines, polyline, quadratic Bézier, rotated group), FILL (Bézier circle, even-odd ring, scaled `use` pads) and CLIPPED (rect cut to its right half by a clipPath), 60 x 20 mm with a 1:1 viewBox.",
        text,
        expect: json!({
            "layers": ["CLIPPED", "FILL", "MARK"],
            "mark_open_paths": 4,
            "mark_widths_mm": [0.2, 0.25, 0.2, 0.1],
            "fill_area_mm2": PI * 25.0 + (120.0 - 48.0) + pads,
            "fill_islands": 4,
            "fill_holes": 1,
            "clipped_area_mm2": 50.0,
            "clipped_bounds_mm": [50.0, 5.0, 55.0, 15.0],
            "bounds_mm": [0.0, 0.0, 60.0, 20.0],
        }),
        notes: vec![
            "y is flipped on import: SVG y grows downwards, the model's y grows upwards",
            "the Bézier circle area is exact to the kappa approximation (about 0.03 %), so the test tolerance is 0.05 mm²",
            "usvg geometry is f32: positions reproduce to about 1e-6 mm, areas to about 1e-4 mm²",
            "stroke widths follow the group scale: the rotated line keeps 0.1 mm, the pads' fill is scaled 1.5x",
        ],
    }
}

pub fn all() -> Vec<SvgFixture> {
    vec![marking()]
}
